def source_standard_include_block(unit: ModuleUnit, text: str, include_own_header: bool) -> list[str]:
    out: list[str] = [f"#include <{CONFIG_HEADER_RELPATH.as_posix()}>\n"]
    headers = set(infer_standard_headers(text, uses_std_compat=unit.uses_std_compat))
    for token in set(STD_TOKEN_RE.findall(text)) & STD_STREAM_TOKENS:
        headers.add(STREAM_TOKEN_HEADER[token])
    if "std::println" in text or "std::print" in text:
        headers.add("print")
    for header in sorted(headers):
        out.append(f"#include <{header}>\n")
    if include_own_header:
        own_header = module_to_header_relpath(unit.module_name.split(":", 1)[0]).as_posix()
        if f"#include <{own_header}>\n" not in out:
            out.append(f"#include <{own_header}>\n")
    return out


def transform_to_module_no_import_source(unit: ModuleUnit) -> str:
    before_decl = list(unit.lines[: unit.declaration_index])
    after_decl = list(unit.lines[unit.declaration_index + 1 :])
    import_prelude, body = module_source_import_prelude(after_decl)
    out: list[str] = ["module;\n", f"{GENERATED_BANNER}\n"]
    for line in before_decl:
        if line.strip() == "module;":
            continue
        out.append(rebase_local_include_line(line))
    out.extend(source_standard_include_block(unit, "".join(after_decl), include_own_header=False))
    out.append("\n")
    export_prefix = "export " if unit.is_interface else ""
    out.append(f"{export_prefix}module {unit.module_name};\n")
    out.extend(import_prelude)
    out.append("\n")
    out.extend(module_overlay_source_line(line) for line in body)
    return "".join(out)


def transform_to_header_mode_source(unit: ModuleUnit, include_own_header: bool = True) -> str:
    before_decl = list(unit.lines[: unit.declaration_index])
    after_decl = list(unit.lines[unit.declaration_index + 1 :])
    import_prelude, body = header_source_import_prelude(unit, after_decl)
    out: list[str] = [f"{GENERATED_BANNER}\n"]
    for line in before_decl:
        if line.strip() == "module;":
            continue
        out.append(rebase_local_include_line(line))
    out.extend(source_standard_include_block(unit, "".join(after_decl), include_own_header=include_own_header))
    out.extend(import_prelude)
    out.append("\n")
    out.extend(header_impl_source_line(header_collision_rewrite(line, unit)) for line in body)
    return "".join(out)


def transform_to_module_no_import_consumer(path: Path) -> str:
    lines = read_lines(path)
    text = "".join(lines)
    stream_headers: set[str] = set()
    if any(token in text for token in ("std::ifstream", "std::ofstream", "std::fstream")):
        stream_headers.add("fstream")
    if any(token in text for token in ("std::istringstream", "std::ostringstream", "std::stringstream")):
        stream_headers.add("sstream")
    if any(token in text for token in ("std::cerr", "std::cout", "std::clog", "std::cin")):
        stream_headers.add("iostream")
    out: list[str] = [
        f"{GENERATED_BANNER}\n",
        f"#include <{CONFIG_HEADER_RELPATH.as_posix()}>\n",
    ]
    for header in sorted(set(infer_standard_headers(text, uses_std_compat="import std.compat;" in text)) | stream_headers):
        out.append(f"#include <{header}>\n")
    if "std::println" in text or "std::print" in text:
        out.append("#include <print>\n")
    out.append("\n")
    for line in lines:
        if line.strip() == "module;" or MODULE_DECL_RE.match(line):
            continue
        match = IMPORT_RE.match(line)
        if match is not None and match.group("name") in {"std", "std.compat"}:
            continue
        out.append(rebase_local_include_line(line))
    return "".join(out)


def transform_to_header_mode_consumer(path: Path, local_imports: dict[str, str] | None = None) -> str:
    local_imports = local_imports or {}
    lines = read_lines(path)
