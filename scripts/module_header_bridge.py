MODULE_DECL_RE = re.compile(r"^(?P<indent>\s*)(?P<export>export\s+)?module\s+(?P<name>[A-Za-z_][A-Za-z0-9_.]*(?::[A-Za-z_][A-Za-z0-9_]*)?)\s*;")
