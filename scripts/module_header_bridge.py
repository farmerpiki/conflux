def write_if_changed(path: Path, content: str, write: bool) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return True



def header_source_include_line(unit: ModuleUnit, name: str) -> list[str]:
    if name in {"std", "std.compat"}:
        return []
    include = import_to_include(name, unit.module_name)
    if include is not None:
        return [f"#include <{include}>\n"]
    return [f"import {name};\n"]


def header_source_import_prelude(unit: ModuleUnit, lines: list[str]) -> tuple[list[str], list[str]]:
    out: list[str] = []
    body_start = 0
    for index, line in enumerate(lines):
        stripped = line.strip()
        match = IMPORT_RE.match(line)
        if match is not None:
            out.extend(header_source_include_line(unit, match.group("name")))
            body_start = index + 1
            continue
        if stripped.startswith("#") or stripped.startswith("//") or stripped == "":
            out.append(line)
            body_start = index + 1
            continue
        break
    while out and out[-1].strip() == "":
        out.pop()
    if out:
        out.append("\n")
    return out, lines[body_start:]


def module_source_import_prelude(lines: list[str]) -> tuple[list[str], list[str]]:
    out: list[str] = []
    body_start = 0
