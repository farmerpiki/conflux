@dataclasses.dataclass(frozen=True)
class ModuleUnit:
    path: Path
    relpath: Path
    module_name: str
    is_interface: bool
    is_partition: bool
    declaration_index: int
    imports: tuple[str, ...]
    export_imports: tuple[str, ...]
    uses_std: bool
    uses_std_compat: bool
    lines: tuple[str, ...]


@dataclasses.dataclass(frozen=True)
class ExportSymbol:
    namespace: str | None
    name: str


def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines(keepends=True)


def discover_module_unit(path: Path, src_root: Path) -> ModuleUnit | None:
    lines = read_lines(path)
    if any(GENERATED_BANNER in line for line in lines):
        return None
    declaration_index = -1
    module_name = ""
    is_interface = False
    for index, line in enumerate(lines):
        match = MODULE_DECL_RE.match(line)
        if match is None:
            continue
        declaration_index = index
        module_name = match.group("name")
        is_interface = bool(match.group("export"))
        break
    if declaration_index < 0:
        return None

    imports: list[str] = []
    export_imports: list[str] = []
    uses_std = False
    uses_std_compat = False
    for line in lines[declaration_index + 1 :]:
        match = IMPORT_RE.match(line)
        if match is None:
            continue
        name = match.group("name")
        is_export = bool(match.group("export"))
        if name == "std":
            uses_std = True
        elif name == "std.compat":
            uses_std_compat = True
        elif is_export:
            export_imports.append(name)
        elif name.startswith(":"):
            imports.append(name)
        else:
            imports.append(name)
    return ModuleUnit(
        path=path,
        relpath=path.relative_to(src_root),
        module_name=module_name,
        is_interface=is_interface,
        is_partition=":" in module_name,
        declaration_index=declaration_index,
        imports=tuple(imports),
        export_imports=tuple(export_imports),
        uses_std=uses_std,
        uses_std_compat=uses_std_compat,
        lines=tuple(lines),
    )


def module_to_header_relpath(module_name: str) -> Path:
    primary, sep, partition = module_name.partition(":")
    parts = primary.split(".")
    if sep:
        return Path(*parts, partition).with_suffix(".hxx")
    return Path(*parts).with_suffix(".hxx")


def import_to_include(import_name: str, owner_module: str | None = None) -> str | None:
    if import_name.startswith(":"):
        if owner_module is None:
            return None
        primary = owner_module.split(":", 1)[0]
        return module_to_header_relpath(f"{primary}{import_name}").as_posix()
    if import_name == "conflux" or any(import_name.startswith(prefix) for prefix in PROJECT_IMPORT_PREFIXES):
        return module_to_header_relpath(import_name).as_posix()
    if any(import_name.startswith(prefix) for prefix in LEGACY_PROJECT_MODULE_PREFIXES):
        return Path(import_name).with_suffix(".hxx").as_posix()
    return None


def infer_standard_headers(text: str, uses_std_compat: bool) -> list[str]:
    headers: set[str] = set()
    seen_tokens = set(STD_TOKEN_RE.findall(text)) | {m.group("name") for m in BARE_STD_TOKEN_RE.finditer(text)}
    unknown_std_tokens: set[str] = set()
    for token in seen_tokens:
        if token in STD_STREAM_TOKENS:
            continue
        token_headers = STD_HEADER_BY_TOKEN.get(token)
        if token_headers is None:
            unknown_std_tokens.add(token)
        else:
            headers.update(token_headers)
    if uses_std_compat:
        headers.update(STD_COMPAT_FALLBACK_HEADERS)
    if unknown_std_tokens:
        headers.update(STD_SAFETY_NET_HEADERS)
    return sorted(headers)


def find_std_stream_tokens(text: str, explicit_headers: set[str] | None = None) -> list[str]:
    explicit_headers = explicit_headers or set()
    seen_tokens = set(STD_TOKEN_RE.findall(text))
    tokens = seen_tokens & STD_STREAM_TOKENS
    return sorted(token for token in tokens if STREAM_TOKEN_HEADER.get(token) not in explicit_headers)


def explicit_std_headers(lines: Iterable[str]) -> set[str]:
    headers: set[str] = set()
    for line in lines:
        stripped = line.strip()
        if not stripped.startswith("#include <"):
            continue
        end = stripped.find(">", len("#include <"))
        if end != -1:
            headers.add(stripped[len("#include <"):end])
    return headers


def angle_include_header(line: str) -> str | None:
    match = ANGLE_INCLUDE_RE.match(line)
    if match is None:
        return None
    return match.group("header")


def is_known_std_header(header: str) -> bool:
    return header in KNOWN_STD_HEADERS


def rebase_local_include_line(line: str) -> str:
    match = LOCAL_INCLUDE_RE.match(line)
    if match is None:
        return line
    rel = Path(match.group("path"))
    if rel.is_absolute() or ".." in rel.parts:
        return line
    target = PRIVATE_INCLUDE_PREFIX / rel
    return f"{match.group('indent')}#include <{target.as_posix()}>\n"

def module_unit_stem(module_name: str) -> str:
    primary, sep, partition = module_name.partition(":")
    stem = "/".join(primary.split("."))
    if sep:
        return f"{stem}/{partition}"
    return stem


def source_line_feature_macros(lines: Iterable[str]) -> list[str]:
    macros: set[str] = set()
    for line in lines:
        match = DIRECT_IF_MACRO_RE.match(line)
        if match is not None:
            macros.add(match.group(1))
    return sorted(macros)


def line_needs_header_inline(line: str) -> bool:
    stripped = line.lstrip()
    if not stripped or stripped.startswith(("//", "#")):
        return False
    if stripped.rstrip().endswith(";"):
        return False
    # Header mode only needs implicit inline for real file-scope definitions.
    # Declarations are intentionally left as declarations because compiled
    # implementation units still provide the out-of-line symbols.
    if "{" not in stripped:
        return False
    semicolon_pos = stripped.find(";")
    brace_pos = stripped.find("{")
    if semicolon_pos != -1 and semicolon_pos < brace_pos:
        return False
    if line[: len(line) - len(stripped)] and not stripped.startswith("export "):
        return False
    probe = stripped.removeprefix("export ")
    probe_no_attrs = re.sub(r"^(?:\[\[[^\]]+\]\]\s*)+", "", probe)
    if probe_no_attrs.startswith((
        "inline ", "static ", "constexpr ", "consteval ", "friend ",
        "class ", "struct ", "union ", "enum ", "namespace ", "using ",
        "template ", "concept ", "requires ", "if ", "for ", "while ", "switch ",
        "return ", "co_return ", "static_assert", "extern ",
    )):
        return False
    match = PROBABLE_FUNCTION_LINE_RE.match(line)
    if match is None:
        return False
    body = match.group("body")
    lhs = body.split("(", 1)[0].strip()
    if lhs == "main" or lhs.endswith(" main"):
        return False
    if "=" in lhs:
        return False
    if "->" in line and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_:]*", lhs):
        return False
    if body.strip().startswith(("auto [", "decltype(")):
        return False
    return True


def headerize_source_line(line: str, force_inline: bool = False) -> str:
    line = rebase_local_include_line(line)
    line = BARE_NULLPTR_T_RE.sub("std::nullptr_t", line)
    if IMPORT_RE.match(line):
        return line
    stripped_original = line.lstrip()
    was_export = stripped_original.startswith("export ")
    line = EXPORT_PREFIX_RE.sub(lambda match: match.group("indent"), line, count=1)
    if was_export:
        stripped = line.lstrip()
        indent = line[: len(line) - len(stripped)]
        variable_like = "(" not in stripped and ("=" in stripped or ";" in stripped or "{" in stripped)
        if variable_like and stripped.startswith("constexpr ") and not stripped.startswith("inline constexpr "):
            return f"{indent}inline {stripped}"
        if variable_like and stripped.startswith("constinit ") and not stripped.startswith("inline constinit "):
            return f"{indent}inline {stripped}"
    if force_inline or line_needs_header_inline(line):
        match = PROBABLE_FUNCTION_LINE_RE.match(line)
        if match is not None:
            body = match.group("body")
            body_prefix = body.split("(", 1)[0]
            if " inline " in f" {body_prefix} ":
                return line
            body_stripped = body.lstrip()
            body_indent = body[: len(body) - len(body_stripped)]
            extern_c_prefix = 'extern "C" '
            if body_stripped.startswith(extern_c_prefix):
                return (
                    f"{match.group('indent')}{match.group('prefix')}"
                    f"{body_indent}{extern_c_prefix}inline "
                    f"{body_stripped.removeprefix(extern_c_prefix)}{match.group('tail')}\n"
                )
            return f"{match.group('indent')}{match.group('prefix')}inline {body}{match.group('tail')}\n"
    return line


def starts_multiline_function_definition(lines: list[str], index: int) -> bool:
    line = lines[index]
    stripped = line.lstrip()
    if line[: len(line) - len(stripped)] and not stripped.startswith("export "):
        return False
    if stripped.startswith((
        "return ", "co_return ", "if ", "for ", "while ", "switch ",
        "requires ", "static_assert", "class ", "struct ", "union ",
        "enum ", "using ", "namespace ", "concept ",
    )):
        return False
    if not stripped.rstrip().endswith("("):
        return False
    if PROBABLE_FUNCTION_LINE_RE.match(line) is None:
        return False
    paren_depth = line.count("(") - line.count(")")
    for next_line in lines[index + 1 :]:
        for char in next_line:
            if char == "(":
                paren_depth += 1
                continue
            if char == ")":
                paren_depth -= 1
                continue
            if paren_depth > 0:
                continue
            if char == "{":
                return True
            if char == ";":
                return False
    return False


def module_overlay_source_line(line: str) -> str:
    line = rebase_local_include_line(line)
    return BARE_NULLPTR_T_RE.sub("std::nullptr_t", line)


def header_impl_source_line(line: str) -> str:
    line = rebase_local_include_line(line)
    line = EXPORT_PREFIX_RE.sub(lambda match: match.group("indent"), line, count=1)
    return BARE_NULLPTR_T_RE.sub("std::nullptr_t", line)


def header_collision_rewrite(line: str, unit: ModuleUnit) -> str:
    prefixes = {
        "conflux.json": "ConfluxJson",
        "conflux.net.response_cache": "ConfluxResponseCache",
    }
    prefix = prefixes.get(unit.module_name)
    if unit.module_name == "conflux.socket_io":
        return re.sub(r"\bFdGuard\b", "ConfluxSocketIoFdGuard", line)
    if prefix is None:
        return line
    line = re.sub(r"\bTransparentStringHash\b", f"{prefix}TransparentStringHash", line)
    line = re.sub(r"\bTransparentStringEqual\b", f"{prefix}TransparentStringEqual", line)
    return line

def std_guard_block(headers: Iterable[str], compat: bool) -> list[str]:
    macro = "CONFLUX_HEADER_USE_IMPORT_STD_COMPAT" if compat else "CONFLUX_HEADER_USE_IMPORT_STD"
    import_name = "std.compat" if compat else "std"
    out = [f"#if defined({macro}) && {macro}\n", f"import {import_name};\n", "#else\n"]
    for header in headers:
        out.append(f"#include <{header}>\n")
    out.append("#endif\n")
    return out


def import_guard_block(import_name: str, exported: bool, for_header: bool, owner_module: str | None = None) -> list[str]:
    include = import_to_include(import_name, owner_module)
    if include is None:
        prefix = "export " if exported and not for_header else ""
        return [f"{prefix}import {import_name};\n"]
    if for_header:
        return [
            "#if defined(CONFLUX_HEADER_USE_MODULE_IMPORTS) && CONFLUX_HEADER_USE_MODULE_IMPORTS\n",
            f"import {import_name};\n",
            "#else\n",
            f"#include <{include}>\n",
            "#endif\n",
        ]
    prefix = "export " if exported else ""
    return [
        "#if defined(CONFLUX_MODULE_REEXPORT_IMPORTS) && CONFLUX_MODULE_REEXPORT_IMPORTS\n" if exported else "#if defined(CONFLUX_MODULE_USE_IMPORTS) && CONFLUX_MODULE_USE_IMPORTS\n",
        f"{prefix}import {import_name};\n",
        "#endif\n",
    ]


def transform_to_header(unit: ModuleUnit) -> tuple[str, list[str]]:
    warnings: list[str] = []
    before_decl = list(unit.lines[: unit.declaration_index])
    after_decl = list(unit.lines[unit.declaration_index + 1 :])
    body_text = "".join(after_decl)
    before_std_headers: set[str] = set()
    before_compat_headers: set[str] = set()
    before_non_std_lines: list[str] = []
    for line in before_decl:
        if line.strip() == "module;":
            continue
        header = angle_include_header(line)
        if header is not None and is_known_std_header(header):
            before_std_headers.add(header)
            continue
        before_non_std_lines.append(rebase_local_include_line(line))
    if re.search(r"\bassert\s*\(", body_text) and "#include <cassert>\n" not in before_non_std_lines:
        before_non_std_lines.append("#include <cassert>\n")
    std_headers = sorted(set(infer_standard_headers(body_text, uses_std_compat=False)) | before_std_headers)
    compat_headers = sorted(set(infer_standard_headers(body_text, uses_std_compat=True)) | before_compat_headers)

    out: list[str] = [
        "#pragma once\n",
        f"{GENERATED_BANNER}\n",
        f"#include <{CONFIG_HEADER_RELPATH.as_posix()}>\n",
        "\n",
    ]
    saw_std = False
    saw_std_compat = False
    if std_headers:
        out.extend(std_guard_block(std_headers, compat=False))
        saw_std = True
    if compat_headers:
        out.extend(std_guard_block(compat_headers, compat=True))
        saw_std_compat = True
    if std_headers or compat_headers:
        out.append("\n")

    # Preserve non-standard GMF includes/extern declarations from the source,
    # except the bare module; marker. They are real header dependencies in
    # compatibility mode.
    out.extend(before_non_std_lines)
    if before_non_std_lines:
        out.append("\n")

    for index, line in enumerate(after_decl):
        match = IMPORT_RE.match(line)
        if match is not None:
            name = match.group("name")
            if name == "std":
                if not saw_std:
                    out.extend(std_guard_block(std_headers, compat=False))
                    saw_std = True
                continue
            if name == "std.compat":
                if not saw_std_compat:
                    out.extend(std_guard_block(compat_headers, compat=True))
                    saw_std_compat = True
                continue
            out.extend(import_guard_block(name, exported=bool(match.group("export")), for_header=True, owner_module=unit.module_name))
            continue
        rewritten = header_collision_rewrite(line, unit)
        out.append(headerize_source_line(rewritten, force_inline=starts_multiline_function_definition(after_decl, index)))

    symbols, symbol_warnings = parse_export_symbols(tuple(after_decl))
    warnings.extend(symbol_warnings)
    stream_tokens = find_std_stream_tokens(body_text, explicit_std_headers(before_decl))
    if stream_tokens:
        warnings.append("std stream tokens intentionally not inferred: " + ", ".join(stream_tokens))

    if not saw_std and unit.uses_std:
        warnings.append("unit marked uses_std but no import std line was transformed")
    if not saw_std_compat and unit.uses_std_compat:
        warnings.append("unit marked uses_std_compat but no import std.compat line was transformed")
    return "".join(out), warnings

def brace_delta(line: str) -> int:
    # This intentionally ignores comments/strings; good enough for export namespace
    # discovery and avoids pretending to be a C++ parser.
    return line.count("{") - line.count("}")


def namespace_is_detail(namespace: str | None) -> bool:
    if namespace is None:
        return False
    return any(part == "detail" or part.endswith("_detail") for part in namespace.split("::"))


