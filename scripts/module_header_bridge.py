def resolve_local_include(src_root: Path, owner: Path, include_name: str) -> Path | None:
    rel = Path(include_name)
    candidates = [owner.parent / rel, src_root / rel, src_root / rel.name]
    for candidate in candidates:
        if candidate.exists() and candidate.is_file():
            return candidate
    return None


def collect_local_includes_from_text(text: str) -> list[str]:
    out: list[str] = []
    for line in text.splitlines(keepends=True):
        match = LOCAL_INCLUDE_RE.match(line)
        if match is not None:
            inc = match.group("path")
            rel = Path(inc)
            if not rel.is_absolute() and ".." not in rel.parts:
                out.append(inc)
    return out


def emit_private_include_headers(
    src_root: Path,
    include_out: Path,
    units: Iterable[ModuleUnit],
    write: bool,
    consumer_roots: Iterable[Path] = (),
) -> tuple[int, list[dict[str, str]]]:
    queue: list[tuple[Path, str]] = []
    for unit in units:
        for line in unit.lines:
            match = LOCAL_INCLUDE_RE.match(line)
            if match is not None:
                queue.append((unit.path, match.group("path")))
    for root in consumer_roots:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*")):
            if not path.is_file():
                continue
            try:
                text = path.read_text(encoding="utf-8")
            except UnicodeDecodeError:
                continue
            for include_name in collect_local_includes_from_text(text):
                queue.append((path, include_name))

    changed = 0
    emitted: list[dict[str, str]] = []
    seen: set[Path] = set()
    while queue:
        owner, include_name = queue.pop(0)
        source = resolve_local_include(src_root, owner, include_name)
        if source is None or source in seen:
            continue
        seen.add(source)
        rel = Path(include_name)
        target_rel = PRIVATE_INCLUDE_PREFIX / rel
        target = include_out / target_rel
        text = source.read_text(encoding="utf-8")
        for nested in collect_local_includes_from_text(text):
            queue.append((source, nested))
        transformed = "".join(rebase_local_include_line(line) for line in text.splitlines(keepends=True))
        content = f"{GENERATED_BANNER}\n" + transformed
        if write_if_changed(target, content, write):
            changed += 1
        try:
            source_label = str(source.relative_to(src_root))
        except ValueError:
            source_label = str(source)
        emitted.append({"source": source_label, "header": str(target), "include": target_rel.as_posix()})
    return changed, emitted

def write_if_changed(path: Path, content: str, write: bool) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return True



