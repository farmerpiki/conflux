@dataclasses.dataclass(frozen=True)
class ModuleUnit:
    path: Path
    relpath: Path
    module_name: str
    is_interface: bool
    is_partition: bool
    declaration_index: int
    imports: tuple[str, ...]
    export_imports: tuple[str, ...]
    uses_std: bool
    uses_std_compat: bool
    lines: tuple[str, ...]


@dataclasses.dataclass(frozen=True)
class ExportSymbol:
    namespace: str | None
    name: str


def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8").splitlines(keepends=True)


def discover_module_unit(path: Path, src_root: Path) -> ModuleUnit | None:
    lines = read_lines(path)
    if any(GENERATED_BANNER in line for line in lines):
        return None
    declaration_index = -1
    module_name = ""
    is_interface = False
    for index, line in enumerate(lines):
        match = MODULE_DECL_RE.match(line)
        if match is None:
            continue
        declaration_index = index
        module_name = match.group("name")
        is_interface = bool(match.group("export"))
        break
    if declaration_index < 0:
        return None

    imports: list[str] = []
    export_imports: list[str] = []
    uses_std = False
    uses_std_compat = False
    for line in lines[declaration_index + 1 :]:
        match = IMPORT_RE.match(line)
        if match is None:
            continue
        name = match.group("name")
        is_export = bool(match.group("export"))
        if name == "std":
            uses_std = True
        elif name == "std.compat":
            uses_std_compat = True
        elif is_export:
            export_imports.append(name)
        elif name.startswith(":"):
            imports.append(name)
        else:
            imports.append(name)
    return ModuleUnit(
        path=path,
        relpath=path.relative_to(src_root),
        module_name=module_name,
        is_interface=is_interface,
        is_partition=":" in module_name,
        declaration_index=declaration_index,
        imports=tuple(imports),
        export_imports=tuple(export_imports),
        uses_std=uses_std,
        uses_std_compat=uses_std_compat,
        lines=tuple(lines),
    )


def module_to_header_relpath(module_name: str) -> Path:
    primary, sep, partition = module_name.partition(":")
    parts = primary.split(".")
    if sep:
        return Path(*parts, partition).with_suffix(".hxx")
    return Path(*parts).with_suffix(".hxx")


def import_to_include(import_name: str, owner_module: str | None = None) -> str | None:
    if import_name.startswith(":"):
        if owner_module is None:
            return None
        primary = owner_module.split(":", 1)[0]
        return module_to_header_relpath(f"{primary}{import_name}").as_posix()
    if import_name == "conflux" or any(import_name.startswith(prefix) for prefix in PROJECT_IMPORT_PREFIXES):
        return module_to_header_relpath(import_name).as_posix()
    if any(import_name.startswith(prefix) for prefix in LEGACY_PROJECT_MODULE_PREFIXES):
        return Path(import_name).with_suffix(".hxx").as_posix()
    return None


def infer_standard_headers(text: str, uses_std_compat: bool) -> list[str]:
    headers: set[str] = set()
    seen_tokens = set(STD_TOKEN_RE.findall(text)) | {m.group("name") for m in BARE_STD_TOKEN_RE.finditer(text)}
    unknown_std_tokens: set[str] = set()
    for token in seen_tokens:
        if token in STD_STREAM_TOKENS:
            continue
        token_headers = STD_HEADER_BY_TOKEN.get(token)
        if token_headers is None:
            unknown_std_tokens.add(token)
        else:
            headers.update(token_headers)
    if uses_std_compat:
        headers.update(STD_COMPAT_FALLBACK_HEADERS)
    if unknown_std_tokens:
        headers.update(STD_SAFETY_NET_HEADERS)
    return sorted(headers)


def find_std_stream_tokens(text: str) -> list[str]:
    seen_tokens = set(STD_TOKEN_RE.findall(text))
    return sorted(seen_tokens & STD_STREAM_TOKENS)


def rebase_local_include_line(line: str) -> str:
    match = LOCAL_INCLUDE_RE.match(line)
    if match is None:
        return line
    rel = Path(match.group("path"))
    if rel.is_absolute() or ".." in rel.parts:
        return line
    target = PRIVATE_INCLUDE_PREFIX / rel
    return f"{match.group('indent')}#include <{target.as_posix()}>\n"

def module_unit_stem(module_name: str) -> str:
    primary, sep, partition = module_name.partition(":")
    stem = "/".join(primary.split("."))
    if sep:
        return f"{stem}/{partition}"
    return stem


def source_line_feature_macros(lines: Iterable[str]) -> list[str]:
    macros: set[str] = set()
    for line in lines:
        match = DIRECT_IF_MACRO_RE.match(line)
        if match is not None:
            macros.add(match.group(1))
    return sorted(macros)


def line_needs_header_inline(line: str) -> bool:
    stripped = line.lstrip()
    if not stripped or stripped.startswith(("//", "#")):
        return False
    if stripped.rstrip().endswith(";"):
        return False
    # Header mode only needs implicit inline for real file-scope definitions.
    # Declarations are intentionally left as declarations because compiled
    # implementation units still provide the out-of-line symbols.
    if "{" not in stripped:
        return False
    semicolon_pos = stripped.find(";")
    brace_pos = stripped.find("{")
    if semicolon_pos != -1 and semicolon_pos < brace_pos:
        return False
    if line[: len(line) - len(stripped)] and not stripped.startswith("export "):
        return False
    probe = stripped.removeprefix("export ")
    probe_no_attrs = re.sub(r"^(?:\[\[[^\]]+\]\]\s*)+", "", probe)
    if probe_no_attrs.startswith((
        "inline ", "static ", "constexpr ", "consteval ", "friend ",
        "class ", "struct ", "union ", "enum ", "namespace ", "using ",
        "template ", "concept ", "requires ", "if ", "for ", "while ", "switch ",
        "return ", "co_return ", "static_assert", "extern ",
    )):
        return False
    match = PROBABLE_FUNCTION_LINE_RE.match(line)
    if match is None:
        return False
    body = match.group("body")
    lhs = body.split("(", 1)[0].strip()
    if lhs == "main" or lhs.endswith(" main"):
        return False
    if "=" in lhs:
        return False
    if "->" in line and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_:]*", lhs):
        return False
    if body.strip().startswith(("auto [", "decltype(")):
        return False
    return True


def headerize_source_line(line: str, force_inline: bool = False) -> str:
    line = rebase_local_include_line(line)
    line = BARE_NULLPTR_T_RE.sub("std::nullptr_t", line)
    if IMPORT_RE.match(line):
        return line
    stripped_original = line.lstrip()
    was_export = stripped_original.startswith("export ")
    line = EXPORT_PREFIX_RE.sub(lambda match: match.group("indent"), line, count=1)
    if was_export:
        stripped = line.lstrip()
        indent = line[: len(line) - len(stripped)]
        variable_like = "(" not in stripped and ("=" in stripped or ";" in stripped or "{" in stripped)
        if variable_like and stripped.startswith("constexpr ") and not stripped.startswith("inline constexpr "):
            return f"{indent}inline {stripped}"
        if variable_like and stripped.startswith("constinit ") and not stripped.startswith("inline constinit "):
            return f"{indent}inline {stripped}"
    if force_inline or line_needs_header_inline(line):
        match = PROBABLE_FUNCTION_LINE_RE.match(line)
        if match is not None:
            body_prefix = match.group("body").split("(", 1)[0]
            if " inline " in f" {body_prefix} ":
                return line
            return f"{match.group('indent')}{match.group('prefix')}inline {match.group('body')}{match.group('tail')}\n"
    return line


def starts_multiline_function_definition(lines: list[str], index: int) -> bool:
    line = lines[index]
    stripped = line.lstrip()
    if line[: len(line) - len(stripped)] and not stripped.startswith("export "):
        return False
    if stripped.startswith((
        "return ", "co_return ", "if ", "for ", "while ", "switch ",
        "requires ", "static_assert", "class ", "struct ", "union ",
        "enum ", "using ", "namespace ", "concept ",
    )):
        return False
    if not stripped.rstrip().endswith("("):
        return False
    if PROBABLE_FUNCTION_LINE_RE.match(line) is None:
        return False
    for next_line in lines[index + 1 :]:
        probe = next_line.strip()
        if not probe:
            continue
        semicolon_pos = probe.find(";")
        brace_pos = probe.find("{")
        if brace_pos != -1 and (semicolon_pos == -1 or brace_pos < semicolon_pos):
            return True
        if semicolon_pos != -1:
            return False
    return False


def module_overlay_source_line(line: str) -> str:
    line = rebase_local_include_line(line)
    return BARE_NULLPTR_T_RE.sub("std::nullptr_t", line)


def header_impl_source_line(line: str) -> str:
    line = rebase_local_include_line(line)
    return BARE_NULLPTR_T_RE.sub("std::nullptr_t", line)


def header_collision_rewrite(line: str, unit: ModuleUnit) -> str:
    prefixes = {
        "conflux.json": "ConfluxJson",
        "conflux.net.response_cache": "ConfluxResponseCache",
    }
    prefix = prefixes.get(unit.module_name)
    if unit.module_name == "conflux.socket_io":
        return re.sub(r"\bFdGuard\b", "ConfluxSocketIoFdGuard", line)
    if prefix is None:
        return line
    line = re.sub(r"\bTransparentStringHash\b", f"{prefix}TransparentStringHash", line)
    line = re.sub(r"\bTransparentStringEqual\b", f"{prefix}TransparentStringEqual", line)
    return line

def std_guard_block(headers: Iterable[str], compat: bool) -> list[str]:
    macro = "CONFLUX_HEADER_USE_IMPORT_STD_COMPAT" if compat else "CONFLUX_HEADER_USE_IMPORT_STD"
    import_name = "std.compat" if compat else "std"
    out = [f"#if defined({macro}) && {macro}\n", f"import {import_name};\n", "#else\n"]
    for header in headers:
        out.append(f"#include <{header}>\n")
    out.append("#endif\n")
    return out


def import_guard_block(import_name: str, exported: bool, for_header: bool, owner_module: str | None = None) -> list[str]:
    include = import_to_include(import_name, owner_module)
    if include is None:
        prefix = "export " if exported and not for_header else ""
        return [f"{prefix}import {import_name};\n"]
    if for_header:
        return [
            "#if defined(CONFLUX_HEADER_USE_MODULE_IMPORTS) && CONFLUX_HEADER_USE_MODULE_IMPORTS\n",
            f"import {import_name};\n",
            "#else\n",
            f"#include <{include}>\n",
            "#endif\n",
        ]
    prefix = "export " if exported else ""
    return [
        "#if defined(CONFLUX_MODULE_REEXPORT_IMPORTS) && CONFLUX_MODULE_REEXPORT_IMPORTS\n" if exported else "#if defined(CONFLUX_MODULE_USE_IMPORTS) && CONFLUX_MODULE_USE_IMPORTS\n",
        f"{prefix}import {import_name};\n",
        "#endif\n",
    ]


def transform_to_header(unit: ModuleUnit) -> tuple[str, list[str]]:
    warnings: list[str] = []
    before_decl = list(unit.lines[: unit.declaration_index])
    after_decl = list(unit.lines[unit.declaration_index + 1 :])
    body_text = "".join(after_decl)
    std_headers = infer_standard_headers(body_text, uses_std_compat=False)
    compat_headers = infer_standard_headers(body_text, uses_std_compat=True)

    out: list[str] = [
        "#pragma once\n",
        f"{GENERATED_BANNER}\n",
        f"#include <{CONFIG_HEADER_RELPATH.as_posix()}>\n",
        "\n",
    ]
    # Preserve GMF includes/extern declarations from the source, except the bare
    # module; marker. They are real header dependencies in compatibility mode.
    for line in before_decl:
        if line.strip() == "module;":
            continue
        out.append(rebase_local_include_line(line))
    if before_decl:
        out.append("\n")

    saw_std = False
    saw_std_compat = False
    for index, line in enumerate(after_decl):
        match = IMPORT_RE.match(line)
        if match is not None:
            name = match.group("name")
            if name == "std":
                if not saw_std:
                    out.extend(std_guard_block(std_headers, compat=False))
                    saw_std = True
                continue
            if name == "std.compat":
                if not saw_std_compat:
                    out.extend(std_guard_block(compat_headers, compat=True))
                    saw_std_compat = True
                continue
            out.extend(import_guard_block(name, exported=bool(match.group("export")), for_header=True, owner_module=unit.module_name))
            continue
        rewritten = header_collision_rewrite(line, unit)
        out.append(headerize_source_line(rewritten, force_inline=starts_multiline_function_definition(after_decl, index)))

    symbols, symbol_warnings = parse_export_symbols(tuple(after_decl))
    warnings.extend(symbol_warnings)
    stream_tokens = find_std_stream_tokens(body_text)
    if stream_tokens:
        warnings.append("std stream tokens intentionally not inferred: " + ", ".join(stream_tokens))
    out.extend(render_namespace_aliases(symbols, exported=False))

    if not saw_std and unit.uses_std:
        warnings.append("unit marked uses_std but no import std line was transformed")
    if not saw_std_compat and unit.uses_std_compat:
        warnings.append("unit marked uses_std_compat but no import std.compat line was transformed")
    return "".join(out), warnings

def brace_delta(line: str) -> int:
    # This intentionally ignores comments/strings; good enough for export namespace
    # discovery and avoids pretending to be a C++ parser.
    return line.count("{") - line.count("}")


def namespace_is_detail(namespace: str | None) -> bool:
    if namespace is None:
        return False
    return any(part == "detail" or part.endswith("_detail") for part in namespace.split("::"))


def symbol_is_probably_template_param(name: str) -> bool:
    return bool(re.fullmatch(r"[A-Z](?:[A-Z0-9_]{0,2})", name)) or name in {
        "T", "U", "V", "F", "M", "R", "H", "Cb", "Owner", "Driver", "Body", "Handler",
    }


def strip_template_prefixes(text: str) -> str:
    out = re.sub(r"\bexport\s+template\s*<[^>]*>\s*", "export ", text, flags=re.DOTALL)
    out = re.sub(r"\btemplate\s*<[^>]*>\s*", "", out, flags=re.DOTALL)
    # Drop requires clauses; they often contain function-call-like text and nested braces.
    out = re.sub(r"\brequires\s+requires\s*\([^)]*\)\s*\{.*?\}\s*", " ", out, flags=re.DOTALL)
    out = re.sub(r"\brequires\s+requires\s*\([^)]*\)\s*\{.*?\n(?=\s*(?:\[\[|auto\b|[A-Za-z_:][A-Za-z0-9_:<>\s,&*]*\s+[A-Za-z_~][A-Za-z0-9_:~]*\s*\())", " ", out, flags=re.DOTALL)
    out = re.sub(r"^\s*(?:export\s+)?requires\s*(?:\([^)]*\)|[^\n]+)\s*", "export ", out, flags=re.DOTALL)
    return out


def normalize_decl_text(text: str) -> str:
    text = "\n".join(part.split("//", 1)[0] for part in text.splitlines())
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.DOTALL)
    return re.sub(r"\s+", " ", text).strip()


def extract_symbol_from_decl(text: str, current_namespace: str | None) -> str | None:
    decl = normalize_decl_text(strip_template_prefixes(text))
    if not decl:
        return None
    decl = re.sub(r"^(?:export\s+)?(?:\[\[[^\]]+\]\]\s*)+", "export ", decl)
    decl = re.sub(r"\s+(?:requires)\s+.*?(?=\{|;|$)", " ", decl)
    patterns = (
        r"\bconcept\s+([A-Za-z_][A-Za-z0-9_]*)\b",
        r"\b(?:class|struct|union)\s+([A-Za-z_][A-Za-z0-9_]*)\b",
        r"\benum\s+(?:class\s+)?([A-Za-z_][A-Za-z0-9_]*)\b",
        r"\busing\s+([A-Za-z_][A-Za-z0-9_]*)\b",
    )
    for pattern in patterns:
        match = re.search(pattern, decl)
        if match is not None:
            return match.group(1)

    # Function-like declarations/definitions. Pick the last viable name before
    # an opening paren before the first body/semicolon; this skips requires(...)
    # and attribute internals while still handling multiline signatures.
    head = re.split(r"[;{]", decl, maxsplit=1)[0]
    candidates = re.findall(r"([A-Za-z_~][A-Za-z0-9_:~]*)\s*\(", head)
    skip = {
        "requires", "decltype", "sizeof", "noexcept", "static_cast", "reinterpret_cast",
        "const_cast", "dynamic_cast", "std::same_as", "std::convertible_to",
    }
    for candidate in reversed(candidates):
        if candidate in skip or candidate.startswith("std::"):
            continue
        name = candidate.rsplit("::", 1)[-1]
        if name and name not in {"operator", "requires"}:
            return name

    # Variable / inline constant. Keep this last so return types do not win.
    var_match = re.search(
        r"\b(?:inline\s+)?(?:constexpr\s+|constinit\s+|const\s+)*[A-Za-z_:][A-Za-z0-9_:<>\s,&*]*\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?:=|\{|;)",
        decl,
    )
    if var_match is not None:
        return var_match.group(1)
    return None



def has_real_function_candidate(text: str) -> bool:
    candidates = re.findall(r"([A-Za-z_~][A-Za-z0-9_:~]*)\s*\(", normalize_decl_text(text))
    skip = {
        "requires", "decltype", "sizeof", "noexcept", "static_cast", "reinterpret_cast",
        "const_cast", "dynamic_cast", "std::same_as", "std::convertible_to",
    }
    return any(c.rsplit("::", 1)[-1] not in skip and not c.startswith("std::") for c in candidates)

def declaration_complete(text: str) -> bool:
    # Good enough for exported API discovery: stop at the first top-level-ish
    # semicolon, or a real function-definition brace. Requires-expressions also
    # contain braces, so a brace is only terminal after a viable function name.
    paren = 0
    angle = 0
    skip_names = {
        "requires", "decltype", "sizeof", "noexcept", "static_cast", "reinterpret_cast",
        "const_cast", "dynamic_cast",
    }
    for index, ch in enumerate(text):
        if ch == "(":
            paren += 1
        elif ch == ")" and paren:
            paren -= 1
        elif ch == "<":
            angle += 1
        elif ch == ">" and angle:
            angle -= 1
        elif ch == ";" and paren == 0:
            if "requires requires" in text[:index] and not has_real_function_candidate(text):
                continue
            return True
        elif ch == "{" and paren == 0:
            if "requires requires" in text[:index]:
                continue
            prefix = normalize_decl_text(text[:index])
            candidates = re.findall(r"([A-Za-z_~][A-Za-z0-9_:~]*)\s*\(", prefix)
            if any(c.rsplit("::", 1)[-1] not in skip_names and not c.startswith("std::") for c in candidates):
                return True
    return False

def parse_export_symbols(lines: tuple[str, ...]) -> tuple[list[ExportSymbol], list[str]]:
    symbols: list[ExportSymbol] = []
    warnings: list[str] = []
    namespace_stack: list[tuple[str, int, bool]] = []
    depth = 0
    pending_decl: list[str] = []
    pending_namespace: str | None = None
    pending_explicit = False

    def current_namespace_name(raw_name: str) -> str:
        if "::" in raw_name or not namespace_stack:
            return raw_name
        return f"{namespace_stack[-1][0]}::{raw_name}"

    def flush_pending() -> None:
        nonlocal pending_decl, pending_namespace, pending_explicit
        if not pending_decl:
            return
        text = "".join(pending_decl)
        symbol = extract_symbol_from_decl(text, pending_namespace)
        if symbol is None:
            if pending_explicit:
                sample = " ".join(x.strip() for x in pending_decl if x.strip())[:120]
                warnings.append(f"could not infer exported declaration near: {sample}")
        elif not symbol_is_probably_template_param(symbol) and symbol not in {"operator", "requires", "detail"}:
            if not namespace_is_detail(pending_namespace):
                symbols.append(ExportSymbol(pending_namespace, symbol))
        pending_decl = []
        pending_namespace = None
        pending_explicit = False

    for raw in lines:
        line = raw.rstrip("\n")
        stripped = line.lstrip()

        namespace_match = NAMESPACE_RE.match(line)
        is_namespace_open = namespace_match is not None
        if is_namespace_open:
            flush_pending()
            ns_name = current_namespace_name(namespace_match.group("name"))
            namespace_stack.append((ns_name, depth + brace_delta(line), stripped.startswith("export namespace")))
            depth += brace_delta(line)
            continue

        current_namespace = namespace_stack[-1][0] if namespace_stack else None
        in_export_namespace = any(item[2] for item in namespace_stack)
        declaration_depth_ok = depth == (namespace_stack[-1][1] if namespace_stack else 0)

        starts_export = stripped.startswith("export ") and not stripped.startswith("export import ")
        starts_implicit_export = in_export_namespace and declaration_depth_ok and stripped and not stripped.startswith(("//", "#", "}", "private:", "public:", "protected:"))
        starts_decl = starts_export or starts_implicit_export

        if pending_decl:
            pending_decl.append(line + "\n")
            if declaration_complete("".join(pending_decl)):
                flush_pending()
        elif starts_decl:
            pending_decl = [line + "\n"]
            pending_namespace = current_namespace
            pending_explicit = starts_export
            if declaration_complete(line):
                flush_pending()

        depth += brace_delta(line)
        while namespace_stack and depth < namespace_stack[-1][1]:
            flush_pending()
            namespace_stack.pop()

    flush_pending()

    unique: list[ExportSymbol] = []
    seen: set[tuple[str | None, str]] = set()
    for symbol in symbols:
        if namespace_is_detail(symbol.namespace) or symbol.name == "detail" or symbol.name.endswith("_detail"):
            continue
        key = (symbol.namespace, symbol.name)
        if key not in seen:
            unique.append(symbol)
            seen.add(key)
    return unique, warnings

def alias_targets_for_global_exports(symbols: list[ExportSymbol]) -> dict[str, list[str]]:
    globals_ = [symbol.name for symbol in symbols if symbol.namespace is None]
    if not globals_:
        return {}
    namespaces = sorted({symbol.namespace for symbol in symbols if symbol.namespace is not None})
    targets: dict[str, list[str]] = {}
    for namespace in namespaces:
        if namespace is not None and namespace.startswith("conflux::") and not namespace.endswith("::detail"):
            targets[namespace] = globals_
    return targets


def render_namespace_aliases(symbols: list[ExportSymbol], exported: bool) -> list[str]:
    targets = alias_targets_for_global_exports(symbols)
    if not targets:
        return []
    out: list[str] = ["\n// Compatibility aliases for declarations kept at global scope in the source module.\n"]
    prefix = "export " if exported else ""
    for namespace, names in targets.items():
        out.append(f"{prefix}namespace {namespace} {{\n")
        for name in names:
            out.append(f"    using ::{name};\n")
        out.append("}\n")
    return out


def wrapper_import_prelude(unit: ModuleUnit) -> list[str]:
    out: list[str] = []
    seen_std = False
    seen_std_compat = False
    in_import_prelude = True
    for line in unit.lines[unit.declaration_index + 1 :]:
        stripped = line.strip()
        match = IMPORT_RE.match(line)
        if match is not None:
            name = match.group("name")
            is_export = bool(match.group("export"))
            if name == "std":
                if not seen_std:
                    out.extend([
                        "#if defined(CONFLUX_MODULE_USE_IMPORT_STD) && CONFLUX_MODULE_USE_IMPORT_STD\n",
                        "import std;\n",
                        "#endif\n",
                    ])
                    seen_std = True
            elif name == "std.compat":
                if not seen_std_compat:
                    out.extend([
                        "#if defined(CONFLUX_MODULE_USE_IMPORT_STD_COMPAT) && CONFLUX_MODULE_USE_IMPORT_STD_COMPAT\n",
                        "import std.compat;\n",
                        "#endif\n",
                    ])
                    seen_std_compat = True
            elif is_export:
                out.extend(import_guard_block(name, exported=True, for_header=False, owner_module=unit.module_name))
            # Plain imports are satisfied by the GMF header include.
            continue
        if stripped.startswith("#") or stripped.startswith("//") or stripped == "":
            if in_import_prelude:
                out.append(line)
            continue
        break
    # Trim trailing vertical whitespace from copied NOLINT/preprocessor prelude.
    while out and out[-1].strip() == "":
        out.pop()
    if out:
        out.append("\n")
    return out


def transform_to_module_wrapper(unit: ModuleUnit, header_relpath: Path) -> tuple[str, list[str]]:
    symbols, warnings = parse_export_symbols(unit.lines[unit.declaration_index + 1 :])
    out: list[str] = [
        "module;\n",
        f"#include <{header_relpath.as_posix()}>\n",
        "\n",
        f"export module {unit.module_name};\n",
    ]
    out.extend(wrapper_import_prelude(unit))
    out.append(f"{GENERATED_BANNER}\n")
    if symbols:
        by_namespace: dict[str | None, list[str]] = {}
        for symbol in symbols:
            by_namespace.setdefault(symbol.namespace, []).append(symbol.name)
        for name in by_namespace.get(None, []):
            out.append(f"export using ::{name};\n")
        for namespace, names in sorted((k, v) for k, v in by_namespace.items() if k is not None):
            out.append(f"export namespace {namespace} {{\n")
            for name in names:
                out.append(f"    using ::{namespace}::{name};\n")
            out.append("}\n")
        out.extend(render_namespace_aliases(symbols, exported=True))
    else:
        if unit.export_imports:
            out.append("// Aggregator module: exported imports are preserved by the wrapper prelude.\n")
        else:
            out.append("// No exported declarations inferred from source; header include carries declarations if any.\n")
    return "".join(out), warnings



